// The library of promoted lessons: one JSON entry per problem, plus a generated index.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** Regenerates src/content/library/index.ts from the entries on disk. */
export function writeLibraryIndex(dir: string) {
  const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
  const name = (f: string) => f.replace(/\.json$/, "").replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
  writeFileSync(join(dir, "index.ts"), `// Generated by scripts/promote.ts. Lessons drafted with AI, checked by the pipeline and reviewed by a person.
import { fromLibrary, type LibraryEntry } from "../draft";
import type { Problem } from "../problems";
${files.map((f) => `import ${name(f)} from "./${f}";`).join("\n")}

export const LIBRARY: Problem[] = ([${files.map((f) => `${name(f)}`).join(", ")}] as unknown as LibraryEntry[]).map(fromLibrary);
`);
}
